import math
import unittest
from PIL import Image
from wlre.services.world.portrait_render import palette_vectors, shade_pixel, circle_mask, render


class PortraitRenderTests(unittest.TestCase):
    def test_palette_groups_preserve_official_order(self):
        v = palette_vectors({1: 123456789, 5: 901234567})
        self.assertEqual(v['_1_0_c_Color'], (1, 2, 3))
        self.assertEqual(v['_1_1_HairColor'], (4, 5, 6))
        self.assertEqual(v['_1_2_SkinColor'], (7, 8, 9))
        self.assertEqual(v['_5_0_p_Color'], (9, 0, 1))
        self.assertEqual(v['_13_EyeColor_'], (2, 3, 4))

    def test_reviewed_shader_instruction_vectors(self):
        # Values from independent interpretation of the pinned D3D bytecode's
        # unkeyworded fragment program, not generated by this implementation.
        cases = [
            ([252, 206, 194, 255], [150, 0, 0, 255],
             [0.9725367536994534, 0.8093149215599978, 0.7626376884244843, 1.44505]),
            ([238, 101, 86, 255], [99, 0, 0, 255],
             [0.9259429179392001, 0.3766727649720978, 0.31478974106531665, 1.44505]),
        ]
        for base, mask, expected in cases:
            actual = shade_pixel([v / 255 for v in base], [v / 255 for v in mask], palette_vectors({}))
            for a, b in zip(actual, expected):
                self.assertAlmostEqual(a, b, places=12)

    def test_hair_change_is_selective(self):
        base = [.6, .5, .4, 1]
        before = shade_pixel(base, [.392, 0, 0, 1], palette_vectors({}))
        after = shade_pixel(base, [.392, 0, 0, 1], palette_vectors({1: 444900444}))
        self.assertGreater(after[0], before[0])
        self.assertLess(after[1], before[1])
        self.assertEqual(shade_pixel(base, [.588, 0, 0, 1], palette_vectors({})),
                         shade_pixel(base, [.588, 0, 0, 1], palette_vectors({1: 444900444})))

    def test_circle_mask_and_transparency(self):
        self.assertEqual(circle_mask(.5, .5, .22, 0), (1, 0))
        self.assertEqual(circle_mask(0, 0, .22, 0), (0, 0))
        material = dict(color_profile='official-mobile-gamma-1296', shader='UI_ProfilePhotoWithMask', keywords=[], use_shape_mask=0,
                        mask_clip=.22, edge_length=0)
        base = Image.new('RGBA', (256, 256), (100, 120, 140, 255))
        mask = Image.new('RGBA', (256, 256), 'white')
        image = render(base, mask, {}, material)
        self.assertEqual(image.getpixel((0, 0))[3], 0)
        self.assertEqual(image.getpixel((128, 128))[3], 255)
        self.assertEqual(base.getpixel((0, 0)), (100, 120, 140, 255))

    def test_requires_explicit_reviewed_color_profile(self):
        image = Image.new('RGBA', (256, 256))
        material = dict(shader='UI_ProfilePhotoWithMask', keywords=[], use_shape_mask=0,
                        mask_clip=.22, edge_length=0)
        for profile in (None, 'pc-linear', 'pc-gamma', 'unknown'):
            material['color_profile'] = profile
            with self.assertRaises(ValueError):
                render(image, image, {}, material)

    def test_reject_unknown_geometry_variant_and_palette(self):
        image = Image.new('RGBA', (256, 256))
        for p in ({0: 1}, {1: -1}, {1: 1000000000}, {'1': 444}, {1: True}):
            with self.assertRaises(ValueError):
                palette_vectors(p)
        with self.assertRaises(ValueError):
            render(image, image, {}, {'shader': 'unknown'})
        with self.assertRaises(ValueError):
            render(image.resize((1, 1)), image, {}, {})


if __name__ == '__main__':
    unittest.main()
