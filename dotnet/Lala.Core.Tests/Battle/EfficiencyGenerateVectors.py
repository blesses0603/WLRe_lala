def json_safe(value):
    if isinstance(value, float) and not math.isfinite(value):
        return 'nan' if math.isnan(value) else 'inf' if value > 0 else '-inf'
    if isinstance(value, dict):
        return {str(k): json_safe(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [json_safe(v) for v in value]
    return value


def cs_json(value):
    return json.dumps(json.dumps(json_safe(value), ensure_ascii=False, separators=(',', ':'), allow_nan=False), ensure_ascii=False)


def cs(value):
    if value is None: return 'null'
    if isinstance(value, float):
        if math.isnan(value): return 'double.NaN'
        if value == math.inf: return 'double.PositiveInfinity'
        if value == -math.inf: return 'double.NegativeInfinity'
        return repr(value) + 'd'
    if isinstance(value, int): return str(value) + 'L'
    return json.dumps(value, ensure_ascii=False)


