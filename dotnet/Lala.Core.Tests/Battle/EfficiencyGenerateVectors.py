class Scenario:
    def __init__(self, name):
        self.name = name
        self.state = State()
        self.state.player = {'role_id': 71, 'name': 'Fixture'}
        self.state.knowledge['player']['stats'] = {'exp': 20000, 'level': 15, 'degree': 0}
        self.state.knowledge['companions'] = {
            '2': {'npc_id': 8002, 'stats': {'exp': 10000, 'level': 12, 'degree': 0, 'name': 'Pet Two'}},
            '3': {'npc_id': 8003, 'stats': {'exp': 22000, 'level': 16, 'degree': 0, 'name': 'Idle Pet'}}}
        self.steps = []

    def event(self, event_type, when=None, reset=False, **payload):
        event = {'type': event_type, **payload}
        if when is not None: event['_observed_at'] = when
        before = {'role_id': self.state.player.get('role_id'), 'name': self.state.player.get('name', '玩家'),
                  'stats': dict(self.state.knowledge['player']['stats']),
                  'companions': {k: {'npc_id': v.get('npc_id'), 'stats': dict(v.get('stats', {}))} for k, v in self.state.knowledge['companions'].items()}}
        if reset: self.state.efficiency = source.defaults()
        with patch.object(source.time, 'monotonic', return_value=1234.5):
            source.observe(self.state, event)
        expected = json.loads(json.dumps(self.state.snapshot()['efficiency']))
        for row in expected['rows'].values():
            row['rates'] = source.rates(row)
            row['level_inferred'] = row.get('level_inferred', False)
            row['degree_inferred'] = row.get('degree_inferred', False)
            row['sample_degree'] = row.get('sample_degree')
        self.steps.append({'knowledge': before, 'event': event, 'reset': reset, 'expected': expected})

    def start(self, when, slot=2, **extra):
        units = [{'pid': 71}]
        if slot is not None: units.append({'pid': 8000 + slot, 'master_id': 71, 'npc_index': slot})
        self.event('battle_start', when, units=units, **extra)

    def exp(self, total, when, slot=2, **overrides):
        stats = self.state.knowledge['player']['stats'] if slot is None else self.state.knowledge['companions'][str(slot)]['stats']
        stats['exp'] = total
        data = dict(entity='self' if slot is None else f'follow:{slot}', human_kind=0 if slot is None else 4, kind=36, parameter=0, value=total)
        data.update(overrides)
        self.event('attribute_set', when, **data)

    def battle(self, total, end, slot=2):
        self.start(end - 2, slot)
        self.exp(total, end - 1, slot)
        self.event('event_end', end)

    def finish(self):
        global sequence_count, step_count
        lines.append('        yield return new object[] { ' + cs(self.name) + ', ' + cs_json(self.steps) + ' };')
        sequence_count += 1
        step_count += len(self.steps)


