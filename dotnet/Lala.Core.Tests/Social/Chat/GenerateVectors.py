def vector(name,steps,queries):
    book=NameBook(); messages=deque(maxlen=200); count=0
    for step in steps:
        event=dict(type='chat_message' if step['kind']=='message' else 'chat_profile',role_id=step['role'],name=step['name'])
        event.update(channel=step.get('channel','世界'),server_id=step.get('server'))
        book.update({},event)
        for row in messages:
            label=plain_text(book.name(row['role'],row['scope']) if row['role'] else '系統')
            if label!=str(row['role']):row['label']=label
        if step['kind']=='message':
            count+=1; scope=name_scope(event)
            messages.append(dict(role=step['role'],scope=scope,label=plain_text(book.name(step['role'],scope) if step['role'] else '系統')))
    return dict(name=name,steps=steps,queries=[dict(role=r,scope=s,label=book.name(r,s)) for r,s in queries],
        names=len(book.names),order=[list(k) for k in book.names],labels=[r['label'] for r in messages],received=count)
