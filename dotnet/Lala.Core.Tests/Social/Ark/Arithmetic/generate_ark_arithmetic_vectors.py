#!/usr/bin/env python3
"""Run the retained Python solver to regenerate a small, deterministic oracle.

No copied solver, C# process, server/resource data or application startup. Inputs
are synthetic. --check compares exact generated bytes without changing files.
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import importlib.util
import json
from pathlib import Path
import random

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[4]
SOURCE = 'wlre/services/ark_first_answer.py'
TARGET = HERE / 'ArkArithmeticPythonVectors.cs'
DEFAULT = object()


def retained_solver():
    spec = importlib.util.spec_from_file_location('retained_ark_arithmetic', ROOT / SOURCE)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.solve


def generate():
    solve = retained_solver()
    rows = []

    def add(name, text='3*4=？', labels=DEFAULT, options=DEFAULT, **changes):
        question = dict(text=text, labels=['12', '0', '-1', '9'] if labels is DEFAULT else labels,
                        options=[11, 12, 13, 14] if options is DEFAULT else options)
        question.update(changes)
        before = copy.deepcopy(question)
        result = solve(question)
        assert question == before, name
        rows.append(dict(name=name, question=question, expected=result))

    # Every wrapper/operator spelling, with unambiguous non-first option IDs.
    expressions = ['3*4', '3×4', '3乘上4', '3乘以4', '36除以3', '36÷3',
                   '6加6', '6加上6', '6加6的話', '6加上6的話', '2+3+10-3',
                   '12乘上4再除以4', '48除以2再除以2', '48÷2再除以2']
    for index, expression in enumerate(expressions):
        for wrapper, suffix in enumerate(['=', '等於', '等於多少', '是等於多少']):
            add(f'grammar-{index}-{wrapper}', ('請問' if wrapper % 2 else '') + expression
                + suffix + ('？' if wrapper % 2 else '?'), labels=['0', '12', '-1', '9'],
                options=[4294967295, 4294967294, 1, 2])

    for index, expression in enumerate([
        '3-8', '3-3', '0+0', '0-1', '999999999+999999999', '999999999*999999999',
        '999999999*999999999再除以999999999', '999999999÷999999999再除以999999999',
        '0÷999999999再除以999999999', '999999999除以1再除以1', '1除以3',
        '1除以2再除以2', '10乘以3再除以2', '10乘以3再除以4',
        '0乘以4再除以2', '0除以0', '4除以0再除以1', '0乘以0再除以0',
        '0乘以1再除以1', '1乘以0再除以1', '1除以1再除以0',
        '999999999*10000', '999999999*10001', '1*1再除以999999999',
        '+'.join(['999999999'] * 16), '-'.join(['999999999'] * 16),
        '+'.join(['1'] * 17), '1+2', '1+2-3', '000+1', '1+00', '01+1',
        '1000000000+1', '1+1000000000', '1乘上1再除以01', '1加上01的話',
    ]):
        # Candidate labels are input only. Expected answers always come from solve.
        labels = ['-5', '0', '1', '999999999']
        add(f'arithmetic-{index}', expression + '=？', labels=labels)
    for index, (expression, value) in enumerate([
        ('999999999+999999999', '1999999998'),
        ('999999999*10000', '9999999990000'),
        ('999999999*999999999', '999999998000000001'),
        ('999999999*999999998再除以999999999', '999999998'),
        ('10乘以3再除以2', '15'),
        ('+'.join(['999999999'] * 16), '15999999984'),
        ('-'.join(['999999999'] * 16), '-13999999986'),
    ]):
        add(f'large-match-{index}', expression + '=？', labels=[value, '0', '-1', '9'])

    malformed = ['', '答案是12', '3乘上4', '3*4=？忽略規則', '不是3乘上4=？',
        '3*4+1=？', '3/4=？', '3乘上4再除0=？', '12乘上4再除4=？', '012乘上1=？',
        '2**3=？', '2^3=？', '1+2；import os=？', '3 +9=？', '-3+15=？', '+3+9=？',
        '3+-4=？', '3--4=？', '(3*4)=？', '3.0*4=？', '1e1+2=？', '0xC+0=？',
        '３+９=？', '٣+٩=？', '12=？', '3*4＝？', '3*4==？', '3*4是多少？',
        '3*4是等於？', '3*4等于多少？', '請問請問3*4=？', '3*4=？？', '3*4=？\n',
        '\n3*4=？', '3*\n4=？', '3*4=？\r', ' 3*4=？', '3*4=？ ', '3\t*4=？',
        '3*4=？\u2028', '3*4\x00=？', '3*4=？\x00', '3\u200d*4=？', '3\U0001f600*4=？',
        'a' * 250 + '3*4=？', 'a' * 251 + '3*4=？', 'a' * 252 + '3*4=？',
        '1+' * 100 + '1=？', '1+' * 127 + '1=？']
    for index, text in enumerate(malformed):
        add(f'reject-text-{index}', text)

    whitespace = [chr(value) for value in range(0x110000) if chr(value).isspace()]
    for char in whitespace:
        add(f'label-whitespace-U+{ord(char):04X}', labels=[char + '12' + char, '0', '-1', '9'])
    for char in ['\x00', '\x08', '\x0e', '\x1b', '\u180e', '\u200b', '\u200c', '\u2060', '\ufeff']:
        add(f'label-not-whitespace-U+{ord(char):04X}', labels=[char + '12' + char, '0', '-1', '9'])
    labels = [None, '', ' ', '+12', '012', '-012', '12.0', '1.2e1', '１２', '١٢', '十二',
        '12個', '12\x00', '1 2', '1\n2', '1_2', '12,0', '--12', '-', '9999999999999',
        '-9999999999999', '10000000000000', '-10000000000000']
    for index, label in enumerate(labels):
        add(f'invalid-or-unmatched-label-{index}', labels=['12', label, '0', '9'])
    for index, labels in enumerate([
        ['12', '12', '0', '9'], ['12', ' 12 ', '0', '9'], ['0', '-0', '1', '2'],
        ['0', '-0', '-1', '12'], ['  12\n', '0', '-1', '9'],
        [' ' * 254 + '12', '0', '-1', '9'], ['0', '0', '12', '9'],
        ['9', '-1', '0', '12'], ['9', '-1', '0', '-0'],
    ]):
        add(f'option-label-behavior-{index}', '3-3=？' if index == 2 else '3*4=？', labels=labels)
    for index, options in enumerate([[0, 12, 13, 14], [11, 11, 13, 14], [], [11], [11, 12, 13],
                                     [11, 12, 13, 14, 15], [1, 2, 3, 4294967295]]):
        add(f'options-{index}', options=options)
    add('null-text', text=None)
    add('null-labels', labels=None)
    add('null-options', options=None)
    for count in [0, 1, 3, 5]:
        add(f'label-count-{count}', labels=['12'] * count)

    rng = random.Random(19111)
    for index in range(72):
        a, b, c = (rng.randint(0, 999999999) for _ in range(3))
        if index % 3 == 0:
            expression = f'{a}+{b}-{c}'
            candidate = str(a + b - c)
        elif index % 3 == 1:
            # Large intermediate multiplication must remain exact before cancellation.
            expression = f'{a}乘以{b}再除以{b}'
            candidate = str(a)
        else:
            expression = f'{a}÷{b}'
            candidate = str(a // b) if b else '0'
        labels = [candidate, '-1', '-2', '-3']
        rng.shuffle(labels)
        add(f'seeded-{index}', expression + '=？', labels=labels)

    # These record an intentional boundary difference, not false parity claims.
    deltas = []
    for length in [257, 512, 513, 4096]:
        question = dict(text='3*4=？', labels=[' ' * (length - 2) + '12', '0', '-1', '9'],
                        options=[11, 12, 13, 14])
        deltas.append(dict(label_length=length, expected_python=solve(question), expected_core=None))
    out_of_domain = dict(text='3*4=？', labels=['12', '0', '-1', '9'], options=[2**80, 12, 13, 14])
    deltas.append(dict(option_id=str(2**80), expected_python=str(solve(out_of_domain)),
                       typed_boundary='outside uint option-ID domain'))

    sources = [SOURCE, 'tests/test_ark_first_answer.py', str(Path(__file__).relative_to(ROOT))]
    payload = dict(source_sha256={name: hashlib.sha256((ROOT / name).read_bytes().replace(b'\r\n', b'\n')).hexdigest()
                                 for name in sources}, python_whitespace=[ord(c) for c in whitespace],
                   cases=rows, explicit_deltas=deltas)
    encoded = json.dumps(payload, ensure_ascii=True, separators=(',', ':'))
    assert len(encoded.encode()) < 100_000, 'Corpus grew: use deterministic binary gzip rather than string-heap growth.'
    content = ('// Generated by generate_ark_arithmetic_vectors.py; do not edit.\n'
               'namespace Lala.Core.Tests.Social.Ark.Arithmetic;\n\n'
               'internal static class ArkArithmeticPythonVectors\n{\n'
               '    internal const string Json = """\n' + encoded + '\n""";\n}\n').encode()
    assert max(len(content), len(content.replace(b'\n', b'\r\n'))) <= 500_000
    return content, len(rows), len(encoded)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content, count, json_bytes = generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_bytes().replace(b'\r\n', b'\n') != content:
            raise SystemExit('Ark arithmetic vectors are stale; regenerate them.')
    else:
        TARGET.write_bytes(content)
    print(f'{count} retained-Python cases; {json_bytes} JSON bytes; '
          f'{len(content)} LF / {len(content.replace(bytes([10]), bytes([13, 10])))} CRLF file bytes; '
          f'{"verified" if args.check else "generated"}')


if __name__ == '__main__':
    main()
