"""Observe retained Eve decorators on the existing synthetic corpus, without saving reports.

Reuses the existing verified payload fixture family rather than copying source bytes.
Only generated test fixtures are written. No user assets, patching, or runtime activation.
"""
from __future__ import annotations
import base64
import gzip
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / 'dotnet/Lala.Core.Tests/TestSupport'))
from gzip_json_fixture import gzip_json_bytes
from wlre.services import parser_diagnostics as diagnostics
from wlre.services.world import eve_v115

rows = []
for path in sorted(Path(__file__).with_name('Fixtures').glob('eve-v115-*.json.gz')):
    for case in json.loads(gzip.decompress(path.read_bytes())):
        raw = base64.b64decode(case['raw']) + bytes(case['zero_padding'])
        # DiagnosticRun construction is in-memory; never call save or diagnostics_session.
        run = diagnostics.DiagnosticRun('unused-in-memory-oracle')
        token = diagnostics._run.set(run)
        try:
            try:
                if case['source'] is None:
                    eve_v115.derive_eve_indexes(raw)
                else:
                    eve_v115.derive_eve_index(raw, case['source'])
            except eve_v115.EveDecodeError as error:
                attached = error.parser_diagnostic
                assert attached == {k: v for k, v in next(iter(run.events.values())).items() if k != 'identity'}
            assert len(run.events) == 1
            rows.append({'name': case['name'], 'source': case['source'], 'expected': next(iter(run.events.values()))})
        finally:
            diagnostics._run.reset(token)

output = ROOT / 'dotnet/Lala.Core.Tests/Diagnostics/Parsing/Fixtures/eve-v115-observations.json.gz'
payload = json.dumps(rows, ensure_ascii=True, separators=(',', ':')).encode()
compressed = gzip_json_bytes(payload.decode())
assert len(compressed) <= 500_000
output.write_bytes(compressed)
source_hashes = {}
for name, path in [('Eve', 'wlre/services/world/eve_v115.py'), ('Diagnostics', 'wlre/services/parser_diagnostics.py')]:
    source_hashes[name] = hashlib.sha256((ROOT / path).read_bytes().replace(b'\r\n', b'\n')).hexdigest()
Path(__file__).with_name('EveDiagnosticPythonVectors.cs').write_text('''// Generated by generate_eve_diagnostic_vectors.py. Actual retained decorators, synthetic corpus only.
using System.Text.Json;
using Lala.Core.Tests.TestSupport;
namespace Lala.Core.Tests.World.Eve;
public static class EveDiagnosticPythonVectors
{
    public const int VectorCount = ''' + str(len(rows)) + ''';
    public const string EveSourceSha256 = "''' + source_hashes['Eve'] + '''";
    public const string DiagnosticsSourceSha256 = "''' + source_hashes['Diagnostics'] + '''";
    public static IEnumerable<object[]> Cases()
    {
        int observationIndex = 0;
        foreach (var original in EvePythonVectors.Cases())
            yield return new object[] { original[0], original[1], original[2], observationIndex++ };
        if (observationIndex != VectorCount)
            throw new InvalidDataException("Eve diagnostic corpus no longer matches the payload fixtures.");
    }

    public static JsonElement ReadExpected(int fixtureIndex, int rowIndex, int observationIndex)
    {
        var original = EvePythonVectors.ReadCase(fixtureIndex, rowIndex);
        var observation = Observations.Value[observationIndex];
        if (observation.GetProperty("name").GetString() != original.GetProperty("name").GetString() ||
            observation.GetProperty("source").GetString() != original.GetProperty("source").GetString())
            throw new InvalidDataException("Eve diagnostic corpus no longer matches the payload fixtures.");
        return observation.GetProperty("expected");
    }

    private static readonly Lazy<JsonElement> Observations = new(ReadObservations);
    private static JsonElement ReadObservations()
    {
        using var document = JsonDocument.Parse(GzipJson.DecodeResource(
            "Lala.Core.Tests.Diagnostics.Parsing.Fixtures.eve-v115-observations.json.gz",
            "''' + hashlib.sha256(compressed).hexdigest() + '''", "''' + hashlib.sha256(payload).hexdigest() + '''"));
        if (document.RootElement.GetArrayLength() != VectorCount)
            throw new InvalidDataException("Unmatched Eve diagnostic observation.");
        return document.RootElement.Clone();
    }
}
''', encoding='utf-8', newline='\n')
print(f'{len(rows)} retained decorator observations; {len(payload)} JSON bytes; {len(compressed)} gzip bytes')
