"""Packet-to-local-state geometry parity using retained Python dispatch_local.

Catalog/alias evidence is injected; no resources, services, transport or requests run.
Detailed S62 furniture remains a house-scoped geometry event despite its typed wrapper.
"""
import json
import os
from pathlib import Path
import struct
import sys
from types import SimpleNamespace
from unittest.mock import patch

os.environ['WLRE_DISABLE_AUTO_CATALOG'] = '1'
sys.path.insert(0, str(Path(__file__).resolve().parents[3]))
from wlre.core.state import State
from wlre.core.state_events import dispatch_local
from wlre.network.protocol import decode
from wlre.network.wire import Packet
from wlre.services.world.obstacle_scope import affects_navigation


def p(fmt, *values): return struct.pack('<' + fmt, *values)

def world(scene):
    return (p('IBHHHBBB IIBB', 17, 1, scene, 8, 9, 2, 3, 4, 5, 6, 7, 1)
            + p('BHI', 1, 8, 9) + bytes(10) + p('H', 10))

def furniture(index=1):
    return p('HHHHHBH', index, 2, 3, 4, 5, 6, 7) + p('11H', *range(11)) + p('BB', 1, 2) + bytes(7)


def project(state):
    snapshot = state.snapshot()
    navigation = snapshot['navigation']
    if navigation.get('house_context') is not None:
        navigation['house_context'].setdefault('sizes', {})
    return dict(phase=state.phase, packet_count=state.packet_count, navigation=navigation)


scenarios = []
catalogs = [None, dict(stage_ids=[101, 10299, 61502], aliases=[61501]),
            dict(stage_ids=[101], aliases=None)]
for catalog_index, catalog in enumerate(catalogs):
    for scene in (None, 101, 999, 10299, 63501, 61501, 61502):
        runtime = None if catalog is None else SimpleNamespace(stages=dict.fromkeys(catalog['stage_ids']))
        aliases = None if catalog is None else catalog['aliases']
        state = State(packet_count=2**70)
        vector = dict(name=f'furniture_scope_{catalog_index}_{scene}', catalog=catalog,
                      initial_count=state.packet_count, steps=[])
        def apply(main, sub, payload=b''):
            event = decode(Packet(main, sub, payload))
            state.packet_count += 1
            dispatch_local(state, event, affects_navigation=affects_navigation)
            vector['steps'].append(dict(main=main, sub=sub, hex=payload.hex().upper(),
                                        kind=event['type'], expected=project(state)))
        with patch('wlre.services.world.dynamic_bundle_runtime.current_runtime', return_value=runtime), \
             patch('wlre.services.world.house_navigation.instance_aliases',
                   side_effect=ValueError('unverified alias order') if aliases is None else None,
                   return_value=dict.fromkeys(aliases or [])):
            if scene is not None: apply(3, 1, world(scene))
            apply(62, 4, p('I', 17))  # Empty snapshot must not invalidate even a known house.
            apply(62, 4, p('I', 99) + furniture())  # No local owner test in Python geometry dispatch.
            apply(62, 1, b'\1' + furniture())
            apply(62, 2, p('H', 1))
            apply(62, 5, p('BHHH', 2, 3, 4, 5))
            apply(62, 76, p('H', 1))
            apply(62, 4, p('I', 99))  # Empty does not clear existing staleness either.
            apply(62, 3, bytes(15))  # Existing shallow fallback stays supported.
            apply(65, 13, bytes(2))
            apply(62, 7, b'\0')  # Ordinary storage/craft observations do not invalidate.
            apply(64, 2, b'\1')
            for index in range(7): apply(62, 2, p('H', index))  # Last ten reasons only.
            if scene is not None:
                apply(12, 1, p('IHHH', 17, scene, 10, 11))
                apply(62, 4, p('I', 17))
                apply(12, 1, p('IHHH', 17, 63502 if scene != 63502 else 63503, 12, 13))
                apply(62, 76, p('H', 3))
            scenarios.append(vector)

lines = ['// Generated by FurnitureGeometryGenerateVectors.py. Offline synthetic evidence only.',
         'namespace Lala.Core.Tests.World;', 'public static class FurnitureGeometryPythonVectors', '{',
         '    public static IEnumerable<object[]> Sequences()', '    {']
for vector in scenarios:
    payload = json.dumps(vector, ensure_ascii=False, separators=(',', ':'), allow_nan=False)
    lines.append('        yield return new object[] { ' + json.dumps(vector['name']) + ', '
                 + json.dumps(payload, ensure_ascii=False) + ' };')
lines += ['    }', '}']
Path(__file__).with_name('FurnitureGeometryPythonVectors.cs').write_text('\n'.join(lines)+'\n', encoding='utf-8')
print(f'Generated {len(scenarios)} scenarios, {sum(len(v["steps"]) for v in scenarios)} packet checkpoints.')
