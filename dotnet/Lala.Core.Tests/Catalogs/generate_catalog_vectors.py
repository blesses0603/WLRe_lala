def cs(value):
    if value is None:
        return "null"
    if isinstance(value, bool):
        return str(value).lower()
    return json.dumps(value, ensure_ascii=True)


def item_record(ident=321, name="測試蘋果😀\0\0", kind_name="雜物", **changes):
    """Independent synthetic packing in documented field order, including nonzero skipped fields."""
    values = dict(kind=1, order=7, icon=4321, shop_icon=5432, attr1=(25, 2, -17),
                  attr2=(26, 3, 450), material=3, level=44, fit=0, special=0,
                  open_used=2, need_level=10, price=4294967295, sell_price=2147483648,
                  restrict=16, skill_link=10023, spares=(8, 9, 10, 11, 65535),
                  description=b"\x00\xd8", size=(2, 3, 4), item_size=(6, 7),
                  time=(0, 0, 0), flags=2)
    values.update(changes)
    out = bytearray()
    offsets = {}

    def pack(fmt, *args):
        out.extend(struct.pack("<" + fmt, *args))

    def skip(count):
        out.extend(b"\xa5" * count)

    def text(key, value):
        offsets[key] = len(out)
        raw = value.encode("utf-16-le")
        pack("H", len(raw))
        out.extend(raw)

    text("name", name)
    pack("B", values["kind"])
    text("kind_name", kind_name)
    offsets["id"] = len(out)
    pack("4H", ident, values["order"], values["icon"], values["shop_icon"])
    skip(8)
    pack("HBiHBi", *values["attr1"], *values["attr2"])
    pack("4B", values["material"], values["level"], values["fit"], values["special"])
    skip(64)
    pack("BBII", values["open_used"], values["need_level"], values["price"], values["sell_price"])
    skip(1)
    pack("H", values["restrict"])
    skip(9)
    pack("6H", values["skill_link"], *values["spares"])
    offsets["description"] = len(out)
    pack("H", len(values["description"]))
    out.extend(values["description"])
    pack("3B", *values["size"])
    skip(2)
    pack("2B", *values["item_size"])
    skip(12 + 3)
    pack("3H", *values["time"])
    skip(4 + 24 + 5)
    pack("B", values["flags"])
    skip(7 + 10 + 7)
    return bytes(out), offsets


