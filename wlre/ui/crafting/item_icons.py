"""Cached crafting sprites with strict 1275-vs-1262 source isolation.

The 1275 private icon ZIP is generated by tools/resources/export_1275_visuals.
Never silently display the 1262 image ZIP or 1262 item-to-sprite mapping when
the 1275 official baseline is selected.
"""
from wlre.paths import RESOURCE_ROOT
from wlre.ui.crafting.icon_cache import DECODED_SPRITES
import json
import zipfile
from collections import OrderedDict
import tkinter as tk
from PIL import ImageTk

BASE = RESOURCE_ROOT
ICON_MAP = json.loads((BASE / 'item_icon_map.json').read_text(encoding='utf-8'))['items']


def official_icon_name(item_id):
    from wlre.services.world.runtime_1275 import active_runtime
    row = active_runtime().item_catalog['items'].get(str(item_id))
    if not isinstance(row, dict):
        return None
    icon = row.get('icon_id')
    return f"s{icon}.png" if type(icon) is int and icon > 0 else None


class ItemIcons:
    def __init__(self, master):
        self.master = master
        self.cache = OrderedDict()
        from wlre.services.world.runtime_1275 import baseline_revision, resource_dir
        self.revision = baseline_revision()
        self.archive = None
        if self.revision == '1275':
            private_zip = resource_dir() / 'item_icons_1275.zip'
            if private_zip.is_file():
                from wlre.services.world.visuals_1275 import verify_private_cache
                verify_private_cache(private_zip, 'icons')
                self.archive = zipfile.ZipFile(private_zip)
            # If not installed, show a transparent placeholder instead of
            # claiming an unverified 1262 PNG belongs to the 1275 client.
        else:
            self.archive = zipfile.ZipFile(BASE / 'item_icons.zip')

    def get(self, item_id, size=64):
        if self.revision == '1275':
            try:
                name = official_icon_name(item_id)
            except (KeyError, OSError, ValueError, TypeError):
                name = None
        else:
            name = ICON_MAP.get(str(item_id), {}).get('icon', 's1000') + '.png'
            if name not in self.archive.NameToInfo:
                name = 's1000.png'
        if self.archive is None or not name or name not in self.archive.NameToInfo:
            key = ('missing', size)
            if key not in self.cache:
                self.cache[key] = tk.PhotoImage(master=self.master, width=size, height=size)
            return self.cache[key]
        key = (name, size)
        if key in self.cache:
            self.cache.move_to_end(key)
            return self.cache[key]
        try:
            canvas = DECODED_SPRITES.get(self.archive, name, size)
            image = ImageTk.PhotoImage(canvas, master=self.master)
        except (KeyError, OSError):
            image = tk.PhotoImage(master=self.master, width=size, height=size)
        self.cache[key] = image
        while len(self.cache) > 128:
            self.cache.popitem(last=False)
        return image

    def close(self):
        if self.archive is not None:
            self.archive.close()
            self.archive = None
        self.cache.clear()
